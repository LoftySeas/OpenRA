		[TestCase(TestName = "DecisionIntervalTicks: zero is rejected at ruleset load")]
		public void DecisionIntervalTicksRejectedAtZero()
		{
			// The production RulesetLoaded guard throws a
			// YamlException for DecisionIntervalTicks <= 0. The
			// test cannot easily stand up a full Ruleset, so it
			// exercises the same validation path via reflection.
			// This pins the contract: a config of 0 must never
			// reach production code, otherwise modulo-by-zero
			// would surface at the first BotTick.
			var method = typeof(StrategicCommanderBotModuleInfo).GetMethod(
