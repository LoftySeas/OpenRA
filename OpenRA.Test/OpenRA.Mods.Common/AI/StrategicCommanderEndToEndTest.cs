		[TestCase(TestName = "Init failure is recorded when the state provider is missing, and BotTick short-circuits")]
		public void InitFailureRecordedWhenStateProviderMissing()
		{
			Log.AddChannel("strategic", null);
			var info = MakeInfo();

			// The TestCommander in this test passes `null` for the
			// state provider to the production GetStateProvider()
			// seam, simulating a missing controller. The commander
			// must record the failure when its init check runs
			// (production runs it from TraitEnabled; the test
			// invokes EnsureInitialized() directly because the
			// trait lifecycle is not bootstrapped in the unit
			// harness) and refuse to evaluate any decision
			// afterwards.
			var controller = new RecordingAttackController(
				new BotAttackReadiness(40, 0),
				new StrategicActionResult("1.0.0", 750, StrategicActionType.Attack, StrategicActionStatus.Executed, StrategicActionReason.None));
			var executor = new TestableExecutor(controller, worldTick: 0);
			var commander = new TestCommander(info, stateProvider: null, executor, worldTick: 0, isReplay: false);
			commander.EnsureInitialized();
			var bot = new FakeBot(new FakeBotInfo("strategic", "Strategic"));

			Assert.That(commander.InitFailed, Is.True,
				"Init failure must be flagged on the commander when the state provider is missing.");
			Assert.That(commander.DecisionLog.Events.Count, Is.EqualTo(1));
			var recorded = commander.DecisionLog.Events[0];
			Assert.That(recorded.ActionType, Is.EqualTo(StrategicActionType.NoOp));
			Assert.That(recorded.Status, Is.EqualTo(StrategicActionStatus.Failed));
			Assert.That(recorded.Reason, Is.EqualTo(StrategicActionReason.PolicyError));
			Assert.That(recorded.ExceptionMessage, Does.Contain("IStrategicStateProvider"),
				"The init-failure event must name the missing component.");

			// BotTick must short-circuit on init failure -- no
			// additional events recorded even across many ticks.
			commander.BotTickPublic(bot, worldTick: 1000);
			Assert.That(commander.DecisionLog.Events.Count, Is.EqualTo(1),
				"BotTick must not record additional decisions while init failure is flagged.");
			Assert.That(controller.RequestCount, Is.EqualTo(0));
		}

