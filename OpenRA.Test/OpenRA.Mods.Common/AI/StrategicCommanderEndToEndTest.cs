	/// <summary>
	/// End-to-end test for the M1 strategic decision loop.
	/// <para>
	/// The test drives the production
	/// <see cref="StrategicCommanderBotModule.EvaluateDecision"/> method
	/// against a real <see cref="RuleAttackPolicy"/> and a real
	/// <see cref="StrategicActionExecutor"/>, with stub
	/// <see cref="IStrategicStateProvider"/> and
	/// <see cref="IBotAttackController"/> implementations substituted
	/// in via the production test seams (the virtual
	/// <c>GetStateProvider / GetExecutor / GetPolicy / GetWorldTick /
	/// GetIsReplay</c> accessors on the commander, and the virtual
	/// <c>FindAttackController</c> accessor on the executor).
	/// </para>
	/// <para>
	/// The production code runs unchanged; the test only substitutes
	/// the actor/player-actor lookups that the production code uses to
	/// discover the state provider and the executor's controller.
	/// The seams are a permanent part of the production classes so
	/// that the same evidence can be regenerated by future batches.
	/// </para>
	/// <para>
	/// The harness does not exercise the world tick driver, because
	/// that path requires a fully-bootstrapped game (SDL platform,
	/// real Player, real Map). The production replay guard is
	/// verified by overriding <c>GetIsReplay</c>; the production
	/// <c>ModularBot</c> activation guard is verified by inspection
	/// of the upstream code.
	/// </para>
	/// </summary>
	[TestFixture]
	sealed class StrategicCommanderEndToEndTest
	{
		sealed class FakeStateProvider : IStrategicStateProvider
		{
			readonly StrategicObservation observation;
			public int CaptureCount;

			public FakeStateProvider(StrategicObservation observation)
			{
				this.observation = observation;
			}

			StrategicObservation IStrategicStateProvider.Capture(IBot bot)
			{
				CaptureCount++;
				return observation;
			}
		}

		sealed class RecordingAttackController : IBotAttackController
		{
			readonly BotAttackReadiness readiness;
			readonly StrategicActionResult response;
			public int RequestCount;
			public IBot LastBot;
			public StrategicAction LastAction;

			public RecordingAttackController(BotAttackReadiness readiness, StrategicActionResult response)
			{
				this.readiness = readiness;
				this.response = response;
			}

			BotAttackReadiness IBotAttackController.GetAttackReadiness() => readiness;

			StrategicActionResult IBotAttackController.RequestAttack(IBot bot, in StrategicAction action)
			{
				RequestCount++;
				LastBot = bot;
				LastAction = action;
				return response;
			}
		}

		sealed class FakeBot : IBot
		{
			public FakeBot(IBotInfo info) { Info = info; }
			public IBotInfo Info { get; }
			public Player Player => null;
			void IBot.Activate(Player p) { }
			void IBot.QueueOrder(Order order) { }
		}

		sealed class FakeBotInfo : IBotInfo
		{
			public FakeBotInfo(string type, string name) { Type = type; Name = name; }
			public string Type { get; }
			public string Name { get; }
		}

		// Drives the real production StrategicActionExecutor against a
		// controlled IBotAttackController, bypassing the production
		// actor/player-actor lookup (which requires a fully-bootstrapped
		// World). The world tick is replaced by an explicit parameter
		// that the test controls.
		sealed class TestableExecutor : StrategicActionExecutor, IStrategicActionExecutor
		{
			readonly IBotAttackController controller;
			readonly int worldTick;

			public TestableExecutor(IBotAttackController controller, int worldTick)
				: base(null, new StrategicActionExecutorInfo())
			{
				this.controller = controller;
				this.worldTick = worldTick;
			}

			internal override IBotAttackController FindAttackController(IBot bot) => controller;
			internal override int GetCurrentWorldTick() => worldTick;
		}

		// Production StrategicCommanderBotModule requires an Actor in
		// its constructor. The test subclass overrides all four seam
		// methods so the real Actor is never dereferenced. The world
		// tick and replay flag are mutable so cadence tests can drive
		// BotTick across multiple simulated ticks. The policy is
		// produced by the production GetPolicy() seam by default, and
		// can be replaced via SetPolicy() for throwing-policy tests.
		sealed class TestCommander : StrategicCommanderBotModule
		{
			readonly IStrategicStateProvider stateProvider;
			readonly IStrategicActionExecutor executor;
			readonly IBotAttackController enabledAttackController;
			IStrategicPolicy policy;

			public int WorldTickValue;
			public bool IsReplayValue;

			public TestCommander(
				StrategicCommanderBotModuleInfo info,
				IStrategicStateProvider stateProvider,
				IStrategicActionExecutor executor,
				int worldTick,
				bool isReplay,
				IBotAttackController enabledAttackController = null)
				: base(null, info)
			{
				this.stateProvider = stateProvider;
				this.executor = executor;
				this.enabledAttackController = enabledAttackController;
				WorldTickValue = worldTick;
				IsReplayValue = isReplay;

				/*
				 * The trait's enabledAtTick defaults to 0 so the
				 * existing 75-tick cadence tests keep their
				 * assumption that the trait was enabled at world
				 * start. Tests that need a different offset call
				 * SetEnabledAtTickForTest().
				 */
				SetEnabledAtTickForTest(0);
			}

			internal override IStrategicStateProvider GetStateProvider() => stateProvider;
			internal override IStrategicActionExecutor GetExecutor() => executor;
			internal override IStrategicPolicy GetPolicy() => policy ?? base.GetPolicy();
			internal override int GetWorldTick() => WorldTickValue;
			internal override bool GetIsReplay() => IsReplayValue;
			internal override IBotAttackController FindEnabledAttackController() => enabledAttackController;

			public void BotTickPublic(IBot bot, int worldTick)
			{
				WorldTickValue = worldTick;
				((IBotTick)this).BotTick(bot);
			}

			public void SetPolicy(IStrategicPolicy newPolicy) { policy = newPolicy; }
		}

		static StrategicObservation MakeObservation(int worldTick, int available, int activeSquads)
		{
			return new StrategicObservation("1.0.0", worldTick, "Multi0", "ra", 0, available, activeSquads);
		}

		static StrategicCommanderBotModuleInfo MakeInfo(int squadSize = 40, int interval = 75)
		{
			return new StrategicCommanderBotModuleInfo
			{
				DecisionIntervalTicks = interval,
				SquadSize = squadSize,
			};
		}

		[TestCase(TestName = "ATTACK request flows policy -> real executor -> IBotAttackController and records EXECUTED")]
		public void AttackRequestFlowsThroughProductionChain()
		{
			Log.AddChannel("strategic", null);

			var info = MakeInfo();

			var fakeState = new FakeStateProvider(MakeObservation(750, 40, 0));
			var controller = new RecordingAttackController(
				new BotAttackReadiness(40, 0),
				new StrategicActionResult(
					"1.0.0", 750,
					StrategicActionType.Attack,
					StrategicActionStatus.Executed,
					StrategicActionReason.None));
			var executor = new TestableExecutor(controller, worldTick: 750);

			var commander = new TestCommander(info, fakeState, executor, worldTick: 750, isReplay: false);
			var bot = new FakeBot(new FakeBotInfo("strategic", "Strategic"));

			commander.EvaluateDecision(bot);

			Assert.That(fakeState.CaptureCount, Is.EqualTo(1),
				"State provider should be invoked exactly once per decision.");
			Assert.That(controller.RequestCount, Is.EqualTo(1),
				"Attack controller should be invoked exactly once when policy emits ATTACK.");
			Assert.That(controller.LastBot, Is.SameAs(bot),
				"Attack controller should be invoked with the supplied IBot.");
			Assert.That(controller.LastAction.Type, Is.EqualTo(StrategicActionType.Attack));

			Assert.That(commander.DecisionLog.Events.Count, Is.EqualTo(1));
			var recorded = commander.DecisionLog.Events[0];
			Assert.That(recorded.ActionType, Is.EqualTo(StrategicActionType.Attack));
			Assert.That(recorded.Status, Is.EqualTo(StrategicActionStatus.Executed));
			Assert.That(recorded.WorldTick, Is.EqualTo(750));
			Assert.That(recorded.SchemaVersion, Is.EqualTo("1.0.0"));
			Assert.That(recorded.BotType, Is.EqualTo("strategic"));
		}

